import { z } from 'zod';

// Тело PUT /prices: цена за вид × контейнер. price — неотрицательное число не более чем
// с двумя знаками после запятой (копейки); дробнее (напр. 1.234) отклоняется как 400.
// Проверка «двух знаков» через эпсилон, а не строгое равенство: v*100 в IEEE-754 даёт
// хвосты (99.99*100 === 9998.999999999998), поэтому сравниваем с округлением по допуску.
export const upsertPriceSchema = z.object({
  speciesId: z.string().uuid(),
  containerId: z.string().uuid(),
  price: z
    .number()
    .nonnegative('цена не может быть отрицательной')
    .refine((v) => Math.abs(v * 100 - Math.round(v * 100)) < 1e-9, {
      message: 'не более двух знаков после запятой',
    }),
});
